/**
 * Bake the Washington State outline that Trend Detective uses to decide
 * whether a clicked point is in its study region.
 *
 *   node scripts/build-washington-region.mjs
 *
 * Source: Natural Earth 1:50m admin-1 states (public/geo). The state's
 * polygons are merged and "closed" (grown then shrunk by a few km) so that
 * Puget Sound, Hood Canal and the San Juan channels count as Washington.
 * The open coast and the borders with Oregon, Idaho and Canada stay put.
 *
 * It also writes the true outline (inlets and islands kept) for drawing the
 * state border on the map.
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import buffer from '@turf/buffer'
import union from '@turf/union'
import { featureCollection } from '@turf/helpers'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CLOSE_KM = 9

const admin1 = JSON.parse(await readFile(path.join(root, 'public/geo/ne_50m_admin_1_states_provinces.geojson'), 'utf8'))
const wa = admin1.features.find((f) => f.properties?.name === 'Washington' && f.properties?.iso_a2 === 'US')
if (!wa) throw new Error('Washington not found in admin-1 GeoJSON')

const parts = wa.geometry.coordinates.map((coords) => ({ type: 'Feature', properties: {}, geometry: { type: 'Polygon', coordinates: coords } }))
let merged = parts[0]
for (const p of parts.slice(1)) merged = union(featureCollection([merged, p])) || merged
const grown = buffer(merged, CLOSE_KM, { units: 'kilometers', steps: 4 })
const closed = buffer(grown, -CLOSE_KM, { units: 'kilometers', steps: 4 })

const polys = closed.geometry.type === 'Polygon' ? [closed.geometry.coordinates] : closed.geometry.coordinates
/** Round a ring to 0.01° (≈1 km), dropping repeated points. */
function roundRing(ring) {
  const out = []
  for (const [x, y] of ring) {
    const pt = [Math.round(x * 100) / 100, Math.round(y * 100) / 100]
    const prev = out[out.length - 1]
    if (!prev || prev[0] !== pt[0] || prev[1] !== pt[1]) out.push(pt)
  }
  return out
}

// Outer rings only, rounded to 0.01°: finer than the ~50 km NASA POWER grid.
const rings = polys.map((poly) => roundRing(poly[0]))
// The real outline, for drawing: every polygon of the source (mainland, islands, Point Roberts).
const outline = wa.geometry.coordinates.map((poly) => roundRing(poly[0])).filter((r) => r.length >= 4)

const xs = rings.flat().map((p) => p[0])
const ys = rings.flat().map((p) => p[1])
const bbox = { west: Math.min(...xs), east: Math.max(...xs), south: Math.min(...ys), north: Math.max(...ys) }

const body = `/* Generated by scripts/build-washington-region.mjs — do not edit by hand. */
/* Natural Earth 1:50m admin-1, Washington State, inland waters closed. */
export const WASHINGTON_BBOX = ${JSON.stringify(bbox)}
/** Outer rings as [lng, lat] pairs, inland waters filled: for testing points. */
export const WASHINGTON_RINGS = ${JSON.stringify(rings)}
/** True state outline as [lng, lat] rings (Puget Sound inlets, islands kept): for drawing. */
export const WASHINGTON_OUTLINE = ${JSON.stringify(outline)}
`
await writeFile(path.join(root, 'src/services/nasaPower/washingtonShape.js'), body)
const count = (rs) => rs.reduce((n, r) => n + r.length, 0)
console.log(`Washington: ${rings.length} test ring(s) / ${count(rings)} points, ${outline.length} outline ring(s) / ${count(outline)} points`, bbox)
